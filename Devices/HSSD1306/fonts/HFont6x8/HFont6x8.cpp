/*
 * The Ukrainian letters, U+0404 through U+0491 - EMPTY, to be drawn by hand.
 *
 * They are NOT in the 0x0410..0x044F block above: Unicode put the letters
 * Russian does not use in the gaps around it, so Є, І, Ї and Ґ are scattered
 * between U+0404 and U+0491. They are stored contiguously here anyway, in a
 * sensible reading order, and the ranges below map the scattered codepoints
 * onto this one table - which is exactly what the range indirection is for.
 */
const uint8_t kUkrainian[] = {
    0x00, 0x1C, 0x2A, 0x49, 0x49, 0x41, // U+0404 Є
    0x00, 0x00, 0x41, 0x7F, 0x41, 0x00, // U+0406 І
    0x00, 0x00, 0x45, 0x7C, 0x45, 0x00, // U+0407 Ї
    0x00, 0x38, 0x54, 0x54, 0x54, 0x44, // U+0454 є
    0x00, 0x00, 0x44, 0x7D, 0x40, 0x00, // U+0456 і
    0x00, 0x00, 0x45, 0x7C, 0x41, 0x00, // U+0457 ї
    0x00, 0x7E, 0x02, 0x02, 0x02, 0x03, // U+0490 Ґ
    0x00, 0x7C, 0x04, 0x04, 0x04, 0x06, // U+0491 ґ
};

/** Bytes per glyph: 6 columns, one page. */
const size_t kGlyphBytes = 6;

/**
 * Every block this font covers. Anything outside them - Greek, emoji, the gaps
 * between the blocks - falls through to the missing-character box.
 *
 * The five Ukrainian entries point at different offsets INTO kUkrainian rather
 * than at tables of their own: a range is a pointer, so five scattered
 * codepoint runs can share one contiguous set of glyphs, and no byte is spent
 * on the Serbian and Macedonian letters that sit between them.
 */
const HFontRange kRanges[] = {
    // 91, not 92: the reference table carries one extra pattern past 'z' that
    // it used as a horizontal rule. It is no character, so no codepoint maps to it.
    {0x20, 91, kLatin},       // ' ' .. 'z'
    {0x0410, 64, kCyrillic},  // 'А' .. 'я'
    {0x0404, 1, kUkrainian + (0 * kGlyphBytes)},  // Є
    {0x0406, 2, kUkrainian + (1 * kGlyphBytes)},  // І Ї
    {0x0454, 1, kUkrainian + (3 * kGlyphBytes)},  // є
    {0x0456, 2, kUkrainian + (4 * kGlyphBytes)},  // і ї
    {0x0490, 2, kUkrainian + (6 * kGlyphBytes)},  // Ґ ґ
};

const size_t kRangeCount = sizeof(kRanges) / sizeof(kRanges[0]);

